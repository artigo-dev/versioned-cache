     * During an outage, how long after the last attempt ended one worker of
     * the server tries the stream again. In milliseconds.
     */
    private const RETRY_MS = 1_000;

    /**
     * What a get() in progress has learnt of its key: its read was a miss that
     * computes without the lock (GET_UNLOCKED, see rules()); its callback
     * computed after its own miss, so the write that follows is the pool's own
     * computation (GET_OWN).
     */
    private const GET_UNLOCKED = 1;
    private const GET_OWN = 2;

    /**
     * How many keys a prune names, reads and judges at a time.
     */
    private const PRUNE_BATCH = 1_000;

    /**
     * How many rules one fetch of the stream asks for: a load from the
     * beginning never holds more than one batch beside the set.
     */
    private const RULES_BATCH = 10_000;

    /**
     * Appends one rule and keeps the stream from growing without bound. The
     * append trims as it goes (XADD ... MINID): rules older than the longest
     * possible item lifetime, counted back from the entry the new one follows,
     * have nothing left alive to match. A rule that matches the whole pool
     * makes every older rule redundant, and the stream is trimmed to it.
     *
     * Each rule records whether it opened the stream: NOMKSTREAM refuses to
     * create one, so a nil reply says there was none, and the rule is
     * appended again as the first of a new stream. A reader that holds an
     * item stamped older than an opening rule knows the stream has lost
     * what the item once saw (see InvalidationRules).
     *
     * It answers the new id, the id it was appended after, and whether it
     * opened the stream: the caller adds the rule to the set it holds only
     * when that set ends at the id it was appended after, or it would skip a
     * rule someone else appended in between.
     *
     * The stream is the only record that an invalidation ever happened, so it
     * carries no TTL: under a volatile-* policy that keeps it out of the
     * eviction pool altogether, where a TTL would make it a candidate like any
     * item. The PERSIST is unconditional, so the stream carries no expiry
     * however it came to exist. Items cannot outlive the rules anyway: their
     * TTL is capped to the retention, and the trim above drops only what
     * nothing alive can match.
     *
     * A script because the trim needs the id XADD just generated; the other
     * two are the guarded write and the range asked of a primary. Sent as a
     * body: an invalidation is rare, and a body needs no script cache to be
     * intact.
     */
    private const SCRIPT_INVALIDATE = <<<'LUA'
        local retention = tonumber(ARGV[2])
        local head = redis.call('XREVRANGE', KEYS[1], '+', '-', 'COUNT', 1)
        local previous = head[1] and head[1][1] or '0-0'
        local floor = math.max(0, tonumber(string.match(previous, '^(%d+)')) - retention)
        local opened = '0'
        local id = redis.call('XADD', KEYS[1], 'NOMKSTREAM', 'MINID', floor, '*', 't', ARGV[1], 'first', '0')

        if not id then
            opened = '1'
            id = redis.call('XADD', KEYS[1], '*', 't', ARGV[1], 'first', '1')
        end

        if ARGV[3] == '1' then
            redis.call('XTRIM', KEYS[1], 'MINID', id)
        end

        redis.call('PERSIST', KEYS[1])

        return {id, previous, opened}
        LUA;

    /**
     * The write that follows a read: lands only where the item's epoch is the
     * one the read saw (none, for an item that had none), and then writes
     * what a plain write writes, with the read's mark. No hash command can
     * compare a field and set others, hence a script. Its arguments are the
     * value, the tags, the mark, the epoch seen, a fresh epoch, the TTL and
     * the guard window, both in milliseconds; it answers 1 when it wrote and 0
     * when it refused.
     *
     * The epoch outlives a short-lived item for the window, so a write that
     * follows an earlier miss is still refused once the item has expired.
     */
    private const SCRIPT_GUARDED_WRITE = <<<'LUA'
        local seen = redis.call('HGET', KEYS[1], 'e') or ''

        if seen ~= ARGV[4] then
            return 0
        end

        if tonumber(ARGV[6]) >= tonumber(ARGV[7]) then
            redis.call('HSETEX', KEYS[1], 'PX', ARGV[6], 'FIELDS', 4, 'v', ARGV[1], 't', ARGV[2], 'm', ARGV[3], 'e', ARGV[5])
            redis.call('PEXPIRE', KEYS[1], ARGV[6])
        else
            redis.call('HSETEX', KEYS[1], 'PX', ARGV[6], 'FIELDS', 3, 'v', ARGV[1], 't', ARGV[2], 'm', ARGV[3])
            redis.call('HSETEX', KEYS[1], 'PX', ARGV[7], 'FIELDS', 1, 'e', ARGV[5])
            redis.call('PEXPIRE', KEYS[1], ARGV[7])
        end

        return 1
        LUA;

    /**
     * The same XRANGE a refresh sends, as a script: EVAL is routed to the
     * primary where a plain XRANGE may go to a replica.
     */
    private const SCRIPT_RANGE = <<<'LUA'
        return redis.call('XRANGE', KEYS[1], ARGV[1], '+', 'COUNT', ARGV[2])
        LUA;

