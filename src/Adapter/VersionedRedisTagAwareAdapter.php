/**
 * Tag invalidation that costs the same whether three items match or three
 * million.
 *
 * Symfony's RedisTagAwareAdapter keeps a SET per tag and, when the tag is
 * invalidated, walks that SET deleting every member - one blocking Lua loop
 * whose length is the number of matched items, during which the single
 * threaded server does nothing else.
 *
 * This adapter never builds that index. An invalidation appends **one rule**
 * to a Redis stream and returns; the work of noticing is deferred to whoever
 * reads next. Every item is written with the stream's last entry id at the
 * time - its watermark - and a read evaluates only the rules newer than that
 * watermark against the item's own tags. A stale item loses its data to the
 * read that finds it and, failing that, expires by its TTL.
 *
 * Ordering is causal rather than clock based: stream ids are generated by the
 * node that owns the stream and are monotonic, so nothing anywhere compares
 * two clocks.
 *
 *     $redis = RedisAdapter::createConnection('redis://127.0.0.1');
 *     $pool = new VersionedRedisTagAwareAdapter($redis);
 *
 *     $pool->invalidateTags(['articles']);   // 4 commands, whatever matches
 *
 * An item is a hash written with HSETEX (Redis 8.0), which sets the fields
 * and their expiry in one command, so there is no way for the data to land
 * without the TTL that keeps it from outliving the rules. The key itself is
 * given the TTL of its longest-lived field, so a volatile-* eviction policy
 * still sees it as evictable.
 *
 * The rules stream, on the other hand, carries no TTL, as Symfony's tag Sets
 * do not: under `volatile-*` or `noeviction` it is never evicted, and one of
 * those is the policy to run. Under `allkeys-*` it can go, and the read path
 * then fails safe - an item stamped with a rule the stream no longer
 * remembers is a miss, never a stale hit - at the price of recomputing the
 * pool once.
 *
 * A write that follows no read of this pool takes the rule set the way a read
 * does, and is stamped with the last rule id of that set; the stream's head is
 * never read for a write. One that follows a read is stamped with the
 * position that read was judged at, so a rule appended elsewhere while the
 * value was computed still judges it stale; this pool's own rules move that
 * position on, so an item committed after its own invalidation is fresh, as
 * Symfony's tag semantics require (TagAwareTestTrait pins it).
 *
 * The rule set is compacted - the newest rule per tag - and, given a cache
 * pool, shared by the workers of a server, so a fresh process (every request,
 * under PHP-FPM) adopts it instead of loading the whole stream before its
 * first hit (see SharedRules). APCu is the default pool where it is enabled;
 * pass false as $rulesCache to keep the set per instance. It is bounded by
 * $rulesMaxTags: past it, a floor takes the place of the oldest rules, and an
 * item older than the floor reads as a miss (see InvalidationRules).
 *
 * An invalidation made here is never served stale on this server while the
 * stream can be read: where the set held ends at the id the rule was appended
 * after, the rule is added to it from the reply and the set is shared for the
 * other workers to adopt - at once by the first invalidation of a request,
 * when the request ends (reset(), or the pool going away) for the later ones;
 * otherwise the set is behind, and a mark beside the shared set keeps every
 * worker of the server from judging by it until it is reloaded. The mark only
 * moves forward (see SharedRules::written()). Without a shared set, another
 * instance sees the rule as one made elsewhere.
 *
 * A write that follows a read is guarded (see get() and MissRecords): every
 * write gives the item a fresh epoch, a delete leaves a tombstone holding a
 * fresh one for $guardWindowSeconds, and the write that follows a miss lands
 * only where the epoch is still the one the miss saw - one script, the only
 * one on the write path. A write refused that way answers false, so a value
 * computed from data that was deleted or invalidated while it was computed is
 * never stored as fresh. A value computed with no rule set held, or after a
 * read of the item that failed, is returned and not stored: nothing could say
 * which rules it has seen. get() computing after its own miss leaves the key
 * as it is; any other write - a plain one, a forced recomputation, a save
 * after a read - deletes it, so the value it was to replace is not served.
 * $guardWindowSeconds = 0 switches the guard off.
 *
 * A tag invalidation is soft unless invalidateTags() is told it is hard.
 * With $softGraceSeconds, a read that finds an item only soft rules reached,
 * the newest less than the grace ago, does not drop it: it is a miss all the
 * same, and is kept for takeAgedItem(), which StaleCache's soft mode serves
 * stale while it is refreshed, until the next read, write or delete of the
 * key, or a clear or a hard invalidation, through this pool. hasItem() and
 * prune() leave such an item on the server. A delete, a clear, a hard rule,
 * the bound's floor and a lost stream stay hard. The age is counted on the
 * server's clock, read once per process.
 *
 * On a cluster read from its replicas (failover=slaves), the item reads and
 * the rule fetches may come from a replica that lags. A lagging item looks
 * older, and a lagging rule arrives late by the lag, on top of $rulesCacheMs;
 * neither can serve a value past an invalidation the set already holds. A
 * replica that answers as if the stream had been lost is not believed: the
 * same range is asked of the primary before anything is dropped.
 *
 * What it is worse at, and there is no getting around any of it:
 *
 * - **Memory comes back lazily.** An invalidated item holds its RAM until a
 *   read drops it or its TTL runs out. Reading a fully invalidated set is
 *   roughly twice the cost of reading a live one, and prune() is what takes
 *   back the items nobody reads again.
 * - **Invalidation made elsewhere becomes visible within `rulesCacheMs` plus
 *   a second**, because a rule set is reused for that long, and for up to a
 *   second more while another worker reloads it; a read that cannot promise
 *   that is a miss. While the stream cannot be read, or a reload has run for
 *   more than a second, every worker serves the set it holds, whatever its
 *   age, and one worker of the server tries the stream again a second after
 *   the last attempt ended. Pass 0 for exact reads, at the price of a reload
 *   for every read that can take the flag.
 * - **`$rulesRetentionSeconds` is the maximum item lifetime**, not only the
 *   default. An item must never outlive the rule that made it stale, or it
 *   would come back from the dead once that rule is trimmed away, so a longer
 *   TTL is capped and a warning is logged.
 * - **No tag index to inspect.** Nothing can be asked which items a tag
 *   names, the way SMEMBERS on a tag SET answers it for RedisTagAwareAdapter.
 *   Symfony's own interface never exposed that, so no API goes with it.
 */
final class VersionedRedisTagAwareAdapter extends AbstractTagAwareAdapter implements PruneableInterface, AgedItemsInterface
{
